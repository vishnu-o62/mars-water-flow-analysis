def process_image(image_file):

    image_name = os.path.splitext(image_file)[0]

    print_header(f"Processing : {image_name}")

    # ------------------------------------------------------
    # Paths
    # ------------------------------------------------------

    original_path = os.path.join(
        IMAGE_FOLDER,
        image_file
    )

    mask_path = os.path.join(
        MASK_FOLDER,
        image_name + "_predicted.png"
    )

    # ------------------------------------------------------
    # Read Images
    # ------------------------------------------------------

    original = cv2.imread(original_path)

    mask = cv2.imread(
        mask_path,
        cv2.IMREAD_GRAYSCALE
    )

    if original is None:

        print("Original image not found.")
        return

    if mask is None:

        print("Prediction mask not found.")
        return

    # ------------------------------------------------------
    # Convert Binary
    # ------------------------------------------------------

    _, mask = cv2.threshold(
        mask,
        127,
        255,
        cv2.THRESH_BINARY
    )

    # ------------------------------------------------------
    # Clean Mask
    # ------------------------------------------------------

    cleaned = clean_mask(mask)

    # ------------------------------------------------------
    # Extract Skeleton
    # ------------------------------------------------------

    skeleton = extract_skeleton(cleaned)

    # ------------------------------------------------------
    # Detect Features
    # ------------------------------------------------------

    endpoints = detect_endpoints(
        skeleton
    )

    branchpoints = detect_branchpoints(
        skeleton
    )

    # ------------------------------------------------------
    # Compute Statistics
    # ------------------------------------------------------

    # stats = compute_statistics(
    #     skeleton,
    #     endpoints,
    #     branchpoints
    # )
    #
    # print_statistics(
    #     image_name,
    #     stats
    # )

    # ------------------------------------------------------
    # Compute Statistics
    # ------------------------------------------------------

    stats = compute_statistics(
        skeleton,
        endpoints,
        branchpoints
    )

    # Print statistics on the console
    print_statistics(
        image_name,
        stats
    )

    # Save statistics to CSV
    # save_statistics_csv(
    #   print("Saving CSV...")
    #     image_name,
    #     stats
    # )

    print("Saving CSV...")

    save_statistics_csv(
        image_name,
        stats
    )

    # ------------------------------------------------------
    # Convert Skeleton to Image
    # ------------------------------------------------------

    skeleton_img = (
        skeleton * 255
    ).astype(np.uint8)

    # ------------------------------------------------------
    # Create Overlay
    # ------------------------------------------------------

    overlay = create_overlay(
        original,
        skeleton
    )

    overlay = draw_feature_points(
        overlay,
        endpoints,
        branchpoints
    )

    # ------------------------------------------------------
    # Save Skeleton
    # ------------------------------------------------------

    skeleton_output = os.path.join(
        OUTPUT_SKELETON,
        image_name + "_skeleton.png"
    )

    cv2.imwrite(
        skeleton_output,
        skeleton_img
    )

    # ------------------------------------------------------
    # Save Overlay
    # ------------------------------------------------------

    overlay_output = os.path.join(
        OUTPUT_OVERLAY,
        image_name + "_overlay.png"
    )

    cv2.imwrite(
        overlay_output,
        overlay
    )

    print("Saved Skeleton :", skeleton_output)
    print("Saved Overlay  :", overlay_output)

    return (
        original,
        mask,
        cleaned,
        skeleton_img,
        overlay,
        image_name
    )

